/// Ride request screen — map picker + Barikoi search + time/flexibility.
/// Saves to Supabase on submit (Step 5).
class RideRequestScreen extends ConsumerStatefulWidget {
  const RideRequestScreen({super.key});

  @override
  ConsumerState<RideRequestScreen> createState() => _RideRequestScreenState();
}

class _RideRequestScreenState extends ConsumerState<RideRequestScreen> {
  LocationResult? _pickup;
  LocationResult? _dropoff;
  TimeOfDay _departureTime = TimeOfDay.now();
  int _flexibilityMinutes = 10;

  bool _submitting = false;
  String? _errorMessage;

  // ── Location search helpers ──────────────────────────────────────────

  Future<void> _searchPickup() async {
    final result = await showLocationSearchSheet(
      context,
      ref,
      hint: 'Search pickup location…',
    );
    if (result != null) setState(() => _pickup = result);
  }

  Future<void> _searchDropoff() async {
    final result = await showLocationSearchSheet(
      context,
      ref,
      hint: 'Search drop-off location…',
    );
    if (result != null) setState(() => _dropoff = result);
  }

  // ── Time picker ──────────────────────────────────────────────────────

  Future<void> _pickTime() async {
    final picked = await showTimePicker(
      context: context,
      initialTime: _departureTime,
    );
    if (picked != null) setState(() => _departureTime = picked);
  }

  // ── Submit to Supabase ───────────────────────────────────────────────

  bool get _canSubmit =>
      _pickup != null && _dropoff != null && !_submitting;

  Future<void> _submit() async {
    if (!_canSubmit) return;
    setState(() {
      _submitting = true;
      _errorMessage = null;
    });

    // Build departure DateTime from today's date + chosen time.
    final now = DateTime.now();
    var depart = DateTime(
      now.year,
      now.month,
      now.day,
      _departureTime.hour,
      _departureTime.minute,
    );
    // If the chosen time is already in the past for today, advance to tomorrow.
    if (depart.isBefore(now)) {
      depart = depart.add(const Duration(days: 1));
    }

    final userId = ref.read(currentUserProvider)?.id;
    if (userId == null) {
      setState(() {
        _submitting = false;
        _errorMessage = 'Not signed in. Please restart the app.';
      });
      return;
    }

    final request = RideRequest(
      id: '',             // generated by Postgres
      riderId: userId,
      pickupLatLng: _pickup!.latLng,
      pickupAddress: _pickup!.address,
      dropLatLng: _dropoff!.latLng,
      dropAddress: _dropoff!.address,
      departAt: depart,
      windowMin: _flexibilityMinutes,
      status: RideRequestStatus.pending,
      createdAt: DateTime.now(),
    );

    try {
      await ref.read(rideRequestRepositoryProvider).insert(request);
      if (!mounted) return;
      // Navigate to My Rides so the user can see their new request.
      context.go(AppRoutes.myRides);
    } on PostgrestException catch (e) {
      setState(() {
        _submitting = false;
        _errorMessage = e.message;
      });
    } catch (e) {
      setState(() {
        _submitting = false;
        _errorMessage = e.toString();
      });
    }
  }

  @override
  Widget build(BuildContext context) {
    final tt = Theme.of(context).textTheme;

    return Scaffold(
      appBar: AppBar(title: const Text('Request a Shared Ride')),
      body: SafeArea(
        child: Column(
          children: [
            // ── Map (top 55%) ────────────────────────────────────────
            Expanded(
              flex: 5,
              child: Padding(
                padding: const EdgeInsets.fromLTRB(12, 8, 12, 0),
                child: MapPicker(
                  pickupLocation: _pickup,
                  dropoffLocation: _dropoff,
                  onPickup: (r) => setState(() => _pickup = r),
                  onDropoff: (r) => setState(() => _dropoff = r),
                ),
              ),
            ),

            // ── Form panel (bottom 45%) ──────────────────────────────
            Expanded(
              flex: 4,
              child: SingleChildScrollView(
                padding:
                    const EdgeInsets.symmetric(horizontal: 16, vertical: 12),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.stretch,
                  children: [
                    _SavingsBanner(),
                    const SizedBox(height: 12),

                    // Pickup field
                    _LocationField(
                      label: 'Pickup',
                      icon: Icons.my_location_rounded,
                      iconColor: AppColors.primary,
                      value: _pickup?.displayLabel,
                      hint: 'Tap map or search…',
                      onTap: _searchPickup,
                    ),
                    const SizedBox(height: 8),

                    // Drop-off field
                    _LocationField(
                      label: 'Drop-off',
                      icon: Icons.location_on_rounded,
                      iconColor: AppColors.secondary,
                      value: _dropoff?.displayLabel,
                      hint: 'Tap map or search…',
                      onTap: _searchDropoff,
                    ),
                    const SizedBox(height: 12),

                    // Time + flexibility row
                    Row(
                      children: [
                        Expanded(
                          child: _TimePickerTile(
                            time: _departureTime,
                            onTap: _pickTime,
                          ),
                        ),
                        const SizedBox(width: 8),
                        _FlexChips(
                          value: _flexibilityMinutes,
                          onChanged: (v) =>
                              setState(() => _flexibilityMinutes = v),
                        ),
                      ],
                    ),
                    const SizedBox(height: 14),

                    // Error banner
                    if (_errorMessage != null) ...[
                      _ErrorBanner(message: _errorMessage!),
                      const SizedBox(height: 10),
                    ],

                    ElevatedButton.icon(
                      onPressed: _canSubmit ? _submit : null,
                      icon: _submitting
                          ? const SizedBox(
                              width: 18,
                              height: 18,
                              child: CircularProgressIndicator(
                                  strokeWidth: 2,
                                  color: AppColors.onPrimary),
                            )
                          : const Icon(Icons.search_rounded),
                      label: Text(
                          _submitting ? 'Submitting…' : 'Find Shared Ride'),
                    ),

                    if (!_canSubmit && !_submitting)
                      Padding(
                        padding: const EdgeInsets.only(top: 6),
                        child: Text(
                          'Tap the map or search to set pickup & drop-off.',
                          style: tt.bodySmall
                              ?.copyWith(color: AppColors.onSurfaceMuted),
                          textAlign: TextAlign.center,
                        ),
                      ),
                  ],
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }
}

